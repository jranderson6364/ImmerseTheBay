/**
 * Partsight renderer: turns a PartsSpec into a to-scale, explodable, pinchable diagram.
 *
 * Units: spec is millimetres; Lens world units are centimetres (mm / 10).
 * Each part = pivot SceneObject (moved by explode) -> mesh child (scaled to dims, rotated by rot_deg)
 * plus a box collider + SIK Interactable on the pivot for pinch selection.
 */
import {Interactable} from "SpectaclesInteractionKit.lspkg/Components/Interaction/Interactable/Interactable"
import {WorldLabel} from "../../Scripts/WorldLabel"
import {
  PALETTE_RGBA,
  PartSpecPart,
  PartsSpec,
  explodeOrder,
  explodedPosition,
  partCallout,
  partStyle,
  rotatedHalfExtent,
  HowItWorksStep
} from "../Core/PartSpec"

const MM_TO_CM = 0.1
const DEG = Math.PI / 180

interface PartNode {
  part: PartSpecPart
  index: number
  order: number
  pivot: SceneObject
  meshObj: SceneObject
  visual: RenderMeshVisual
  material: Material
  baseColor: vec4
  label: SceneObject | null
  line: SceneObject | null
  /** Extra local offset (cm) and rotation from how-it-works step playback. */
  stepOffset: vec3
  stepRot: quat
}

@component
export class PartsightRenderer extends BaseScriptComponent {
  @ui.label('<span style="color: #60A5FA;">Partsight Renderer</span><br/><span style="color: #94A3B8; font-size: 11px;">Builds the exploded diagram from a parts spec. Meshes come from Assets/Partsight/Meshes (generated by tools/gen-unit-meshes.ts).</span>')
  @ui.separator
  @input camera: SceneObject
  @input solidMaterial: Material
  @input
  @hint("Transparent material for ghost shells and low-confidence (likely) parts. Falls back to solidMaterial with low alpha.")
  @allowUndefined
  ghostMaterial: Material
  @input
  @hint("Prefab with a WorldLabel component (Assets/Prefabs/WorldLabel.prefab)")
  labelPrefab: ObjectPrefab
  @input labelScale: number = 0.35
  @input showLeaderLines: boolean = true

  @ui.group_start("Unit meshes (ps_*.obj)")
  @input meshBox: RenderMesh
  @input @allowUndefined meshRbox: RenderMesh
  @input @allowUndefined meshCylinder: RenderMesh
  @input @allowUndefined meshTube: RenderMesh
  @input @allowUndefined meshCapsule: RenderMesh
  @input @allowUndefined meshCone: RenderMesh
  @input @allowUndefined meshSphere: RenderMesh
  @input @allowUndefined meshTorus: RenderMesh
  @input @allowUndefined meshUShape: RenderMesh
  @input @allowUndefined meshSpring: RenderMesh
  @input @allowUndefined meshGear: RenderMesh
  @ui.group_end

  /** Fired when the wearer pinches a part. */
  public onPartSelected: (part: PartSpecPart) => void = null

  private root: SceneObject = null
  private nodes: PartNode[] = []
  private spec: PartsSpec = null
  private explodeTarget = 0
  private explodeCurrent = 0
  private selectedId: string = null
  private pulseIds: string[] = []
  private pulseTime = 0
  private stepAnim: {step: HowItWorksStep; t: number} = null

  onAwake() {
    this.createEvent("UpdateEvent").bind(() => this.onUpdate())
  }

  get currentSpec(): PartsSpec {
    return this.spec
  }

  get explodeAmount(): number {
    return this.explodeTarget
  }

  /** Builds the diagram. worldCenter in cm; worldRotation maps spec axes to the real object. */
  build(spec: PartsSpec, worldCenter: vec3, worldRotation: quat) {
    this.clear()
    this.spec = spec
    this.root = global.scene.createSceneObject("Partsight_" + spec.object_name)
    this.root.setParent(this.getSceneObject())
    const t = this.root.getTransform()
    t.setWorldPosition(worldCenter)
    t.setWorldRotation(worldRotation)
    t.setWorldScale(vec3.one())

    const order = explodeOrder(spec.parts)
    spec.parts.forEach((part, i) => this.nodes.push(this.buildPart(part, i, order[i], spec)))
    this.explodeCurrent = 0
    this.explodeTarget = 0
    this.applyLayout()
  }

  clear() {
    if (this.root) this.root.destroy()
    this.root = null
    this.nodes = []
    this.spec = null
    this.selectedId = null
    this.stepAnim = null
  }

  /** 0 = assembled (overlays the real object), 1 = exploded, up to 2 = "explode more". */
  setExplode(t: number) {
    this.explodeTarget = Math.max(0, Math.min(2, t))
  }

  setExplodeImmediate(t: number) {
    this.setExplode(t)
    this.explodeCurrent = this.explodeTarget
  }

  /** Rotate the diagram about its own vertical axis (degrees). */
  rotateBy(deg: number) {
    if (!this.root) return
    const tr = this.root.getTransform()
    tr.setWorldRotation(quat.angleAxis(deg * DEG, vec3.up()).multiply(tr.getWorldRotation()))
  }

  /** Uniform zoom of the whole diagram (1 = true scale). Labels keep their size. */
  setZoom(z: number) {
    if (!this.root) return
    const s = Math.max(0.25, Math.min(6, z))
    this.root.getTransform().setWorldScale(new vec3(s, s, s))
  }

  getZoom(): number {
    return this.root ? this.root.getTransform().getWorldScale().x : 1
  }

  getRoot(): SceneObject {
    return this.root
  }

  select(partId: string) {
    this.selectedId = partId
    this.nodes.forEach((n) => this.applyColor(n, n.part.id === partId ? 1.0 : partId ? 0.35 : 1.0))
  }

  /** Briefly pulse parts (used when an answer or step refers to them). */
  pulse(partIds: string[]) {
    this.pulseIds = partIds.slice()
    this.pulseTime = 1.6
  }

  playStep(step: HowItWorksStep) {
    this.stepAnim = {step, t: 0}
    this.pulse(step.part_ids)
  }

  // -------------------------------------------------------------------------

  private meshFor(shape: string): RenderMesh {
    const m: Record<string, RenderMesh> = {
      box: this.meshBox,
      plate: this.meshBox,
      rbox: this.meshRbox,
      ghost_shell: this.meshRbox || this.meshCapsule,
      cylinder: this.meshCylinder,
      tube: this.meshTube || this.meshCylinder,
      capsule: this.meshCapsule || this.meshCylinder,
      cone: this.meshCone || this.meshCylinder,
      sphere: this.meshSphere,
      torus: this.meshTorus || this.meshTube,
      u_shape: this.meshUShape || this.meshTorus,
      spring: this.meshSpring || this.meshCylinder,
      gear: this.meshGear || this.meshCylinder
    }
    return m[shape] || this.meshBox
  }

  private buildPart(part: PartSpecPart, index: number, order: number, spec: PartsSpec): PartNode {
    const pivot = global.scene.createSceneObject("part_" + part.id)
    pivot.setParent(this.root)

    const meshObj = global.scene.createSceneObject("mesh")
    meshObj.setParent(pivot)
    const mt = meshObj.getTransform()
    mt.setLocalScale(new vec3(part.dims_mm.x * MM_TO_CM, part.dims_mm.y * MM_TO_CM, part.dims_mm.z * MM_TO_CM))
    mt.setLocalRotation(eulerXYZ(part.rot_deg))

    const style = partStyle(part, spec)
    const visual = meshObj.createComponent("Component.RenderMeshVisual") as RenderMeshVisual
    visual.mesh = this.meshFor(part.shape)
    const baseMat = style !== "solid" && this.ghostMaterial ? this.ghostMaterial : this.solidMaterial
    const material = baseMat.clone()
    visual.mainMaterial = material
    const rgba = PALETTE_RGBA[part.color] || PALETTE_RGBA.grey
    const alpha = style === "ghost" ? 0.18 : style === "dashed" ? 0.45 : 1.0
    const baseColor = new vec4(rgba[0], rgba[1], rgba[2], alpha)
    try {
      material.mainPass.baseColor = baseColor
    } catch (e) {
      print("[Partsight] material has no baseColor: " + e)
    }

    // Selection: collider sized to the rotated part, plus a SIK Interactable.
    if (part.shape !== "ghost_shell" || spec.parts.length === 1) {
      const e = rotatedHalfExtent(part.dims_mm, part.rot_deg)
      const collider = pivot.createComponent("Physics.ColliderComponent") as ColliderComponent
      const box = Shape.createBoxShape()
      const minCm = 1.2 // keep tiny parts pinchable
      box.size = new vec3(
        Math.max(minCm, e.x * 2 * MM_TO_CM),
        Math.max(minCm, e.y * 2 * MM_TO_CM),
        Math.max(minCm, e.z * 2 * MM_TO_CM)
      )
      collider.shape = box
      collider.fitVisual = false
      const interactable = pivot.createComponent(Interactable.getTypeName()) as Interactable
      interactable.onTriggerStart.add(() => {
        this.select(part.id)
        if (this.onPartSelected) this.onPartSelected(part)
      })
    }

    let label: SceneObject = null
    let line: SceneObject = null
    if (this.labelPrefab && part.shape !== "ghost_shell") {
      // WorldLabel animates its own scale to 1, so size it through a holder object.
      label = global.scene.createSceneObject("label_" + part.id)
      label.setParent(this.root)
      label.getTransform().setLocalScale(vec3.one().uniformScale(this.labelScale))
      const inner = this.labelPrefab.instantiate(label)
      const wl = inner.getComponent(WorldLabel.getTypeName()) as WorldLabel
      if (wl && wl.textComp) wl.textComp.text = partCallout(part, index, spec)
      label.enabled = false
      if (this.showLeaderLines) {
        line = global.scene.createSceneObject("leader")
        line.setParent(this.root)
        const lv = line.createComponent("Component.RenderMeshVisual") as RenderMeshVisual
        lv.mesh = this.meshBox
        const lm = this.solidMaterial.clone()
        try {
          lm.mainPass.baseColor = new vec4(0.9, 0.9, 0.95, 0.8)
        } catch (e) {}
        lv.mainMaterial = lm
        line.enabled = false
      }
    }

    return {
      part,
      index,
      order,
      pivot,
      meshObj,
      visual,
      material,
      baseColor,
      label,
      line,
      stepOffset: vec3.zero(),
      stepRot: quat.quatIdentity()
    }
  }

  private applyColor(n: PartNode, brightness: number) {
    const c = n.baseColor
    try {
      n.material.mainPass.baseColor = new vec4(c.x * brightness, c.y * brightness, c.z * brightness, c.w)
    } catch (e) {}
  }

  private onUpdate() {
    if (!this.root || this.nodes.length === 0) return
    const dt = getDeltaTime()
    // Critically damped-ish smoothing toward the target explode amount.
    this.explodeCurrent += (this.explodeTarget - this.explodeCurrent) * Math.min(1, dt * 6)
    this.updateStepAnim(dt)
    this.applyLayout()
    this.updatePulse(dt)
    this.faceLabels()
  }

  private applyLayout() {
    const count = this.nodes.length
    const t = this.explodeCurrent
    const showLabels = t > 0.15
    const maxDim = Math.max(this.spec.overall_mm.x, this.spec.overall_mm.y, this.spec.overall_mm.z)
    for (const n of this.nodes) {
      const p = explodedPosition(n.part, n.order, count, t)
      const local = new vec3(p.x * MM_TO_CM, p.y * MM_TO_CM, p.z * MM_TO_CM).add(n.stepOffset)
      const pt = n.pivot.getTransform()
      pt.setLocalPosition(local)
      pt.setLocalRotation(n.stepRot)

      if (n.label) {
        n.label.enabled = showLabels
        // Label sits beyond the part, along its explode direction, raised slightly.
        const ev = new vec3(n.part.explode_mm.x, n.part.explode_mm.y, n.part.explode_mm.z)
        const dir = ev.length > 0.001 ? ev.normalize() : vec3.up()
        const e = rotatedHalfExtent(n.part.dims_mm, n.part.rot_deg)
        const reach = (Math.max(e.x, e.y, e.z) + maxDim * 0.12) * MM_TO_CM
        const labelPos = local.add(dir.uniformScale(reach)).add(new vec3(0, 1.0, 0))
        n.label.getTransform().setLocalPosition(labelPos)
        if (n.line) {
          n.line.enabled = showLabels
          setSegment(n.line, local, labelPos, 0.06)
        }
      }
    }
  }

  private faceLabels() {
    if (!this.camera) return
    const camT = this.camera.getTransform()
    const look = quat.lookAt(camT.right.cross(vec3.up()), vec3.up())
    for (const n of this.nodes) if (n.label && n.label.enabled) n.label.getTransform().setWorldRotation(look)
  }

  private updatePulse(dt: number) {
    if (this.pulseTime <= 0) return
    this.pulseTime -= dt
    const k = 1 + 0.6 * Math.max(0, Math.sin(this.pulseTime * 10))
    for (const n of this.nodes) {
      if (this.pulseIds.indexOf(n.part.id) >= 0) this.applyColor(n, this.pulseTime > 0 ? k : 1)
    }
    if (this.pulseTime <= 0) this.select(this.selectedId)
  }

  /** Plays one how-it-works step: out and back over ~1.6 s. */
  private updateStepAnim(dt: number) {
    if (!this.stepAnim) return
    const a = this.stepAnim
    a.t += dt / 1.6
    const k = Math.sin(Math.min(1, a.t) * Math.PI) // 0 -> 1 -> 0
    const axis = a.step.axis === "y" ? new vec3(0, 1, 0) : a.step.axis === "z" ? new vec3(0, 0, 1) : new vec3(1, 0, 0)
    for (const n of this.nodes) {
      if (a.step.part_ids.indexOf(n.part.id) < 0) continue
      if (a.step.action === "slide" || a.step.action === "press" || a.step.action === "release") {
        n.stepOffset = axis.uniformScale(a.step.amount * MM_TO_CM * k)
      } else if (a.step.action === "rotate") {
        n.stepRot = quat.angleAxis(a.step.amount * DEG * k, axis)
      } else if (a.step.action === "compress") {
        // Squash the mesh along the axis.
        const base = new vec3(n.part.dims_mm.x, n.part.dims_mm.y, n.part.dims_mm.z).uniformScale(MM_TO_CM)
        const squash = 1 - 0.35 * k
        const s = a.step.axis === "y" ? new vec3(base.x, base.y * squash, base.z) : a.step.axis === "z" ? new vec3(base.x, base.y, base.z * squash) : new vec3(base.x * squash, base.y, base.z)
        n.meshObj.getTransform().setLocalScale(s)
      }
    }
    if (a.t >= 1) {
      for (const n of this.nodes) {
        n.stepOffset = vec3.zero()
        n.stepRot = quat.quatIdentity()
        n.meshObj.getTransform().setLocalScale(new vec3(n.part.dims_mm.x, n.part.dims_mm.y, n.part.dims_mm.z).uniformScale(MM_TO_CM))
      }
      this.stepAnim = null
    }
  }
}

/** Euler degrees applied X, then Y, then Z (matches PartSpec.rotatedHalfExtent). */
export function eulerXYZ(r: {x: number; y: number; z: number}): quat {
  const qx = quat.angleAxis(r.x * DEG, vec3.right())
  const qy = quat.angleAxis(r.y * DEG, vec3.up())
  const qz = quat.angleAxis(r.z * DEG, new vec3(0, 0, 1))
  return qz.multiply(qy.multiply(qx))
}

/** Stretches a unit box between two local points to draw a leader line. */
function setSegment(obj: SceneObject, a: vec3, b: vec3, thicknessCm: number) {
  const d = b.sub(a)
  const l = Math.max(0.001, d.length)
  const t = obj.getTransform()
  t.setLocalPosition(a.add(b).uniformScale(0.5))
  t.setLocalRotation(quat.rotationFromTo(vec3.right(), d.uniformScale(1 / l)))
  t.setLocalScale(new vec3(l, thicknessCm, thicknessCm))
}
