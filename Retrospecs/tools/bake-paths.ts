/**
 * Bakes central Stanford's OpenStreetMap roads, bike paths and foot paths into a compact TypeScript data module
 * for the Retrospecs map. Separate from bake-campus.ts on purpose: CampusData.ts is never touched, so landmark
 * building indices stay put.
 *
 *   bun Retrospecs/tools/bake-paths.ts            # uses the cached Overpass response if present
 *   bun Retrospecs/tools/bake-paths.ts --refresh  # re-downloads from Overpass
 *
 * Output: Retrospecs/Assets/Retrospecs/Data/PathsData.ts
 *   - every drawable highway way within BAKE_RADIUS_M of the campus origin, classified (tools/path-classify.ts),
 *     simplified (Douglas-Peucker, SIMPLIFY_M) and quantised to decimetres east/north of the origin, using the same
 *     projection as the buildings (Core/Geo.ts latLonToEN, constants from CampusData.ts).
 *
 * Map data (c) OpenStreetMap contributors, ODbL 1.0. https://www.openstreetmap.org/copyright
 */
import {existsSync, mkdirSync, readFileSync, writeFileSync} from "node:fs"
import {dirname, join} from "node:path"
import {fileURLToPath} from "node:url"
import {latLonToEN} from "../Assets/Retrospecs/Core/Geo"
import {KIND_BIKE, KIND_FOOT, KIND_ROAD, KIND_ROAD_BIKELANE, classifyWay, simplifyDP} from "./path-classify"

const HERE = dirname(fileURLToPath(import.meta.url))
const CACHE = join(HERE, "cache", "stanford_paths_osm.json")
const OUT = join(HERE, "..", "Assets", "Retrospecs", "Data", "PathsData.ts")

// Same bbox as bake-campus.ts (S,W,N,E), which covers 1100 m around Huang.
const BBOX = "37.4175,-122.1885,37.4405,-122.1600"
/** Ways are cut to this radius around the origin. The Lens shows radiusM (700 by default) around the wearer. */
const BAKE_RADIUS_M = 950
const SIMPLIFY_M = 1.2
const MAX_BYTES = 400 * 1024

type XY = [number, number]
interface OsmEl {
  type: string
  id: number
  tags?: Record<string, string>
  geometry?: {lat: number; lon: number}[]
}

async function loadOsm(refresh: boolean): Promise<{elements: OsmEl[]}> {
  if (!refresh && existsSync(CACHE)) return JSON.parse(readFileSync(CACHE, "utf8"))
  const query = `[out:json][timeout:90];way["highway"](${BBOX});out tags geom;`
  let lastErr = ""
  // The main instance is often at capacity; back off and try the public mirrors.
  for (let attempt = 0; attempt < 6; attempt++) {
    const endpoint = ENDPOINTS[attempt % ENDPOINTS.length]
    try {
      const res = await fetch(endpoint, {
        method: "POST",
        headers: {"Content-Type": "application/x-www-form-urlencoded", "User-Agent": "retrospecs-paths-bake/0.1", Accept: "application/json"},
        body: "data=" + encodeURIComponent(query)
      })
      const text = await res.text()
      if (res.ok && text.trimStart().startsWith("{")) {
        mkdirSync(dirname(CACHE), {recursive: true})
        writeFileSync(CACHE, text)
        console.log(`fetched ${(text.length / 1024).toFixed(0)} KB from ${endpoint}`)
        return JSON.parse(text)
      }
      lastErr = `${endpoint} ${res.status}: ${text.slice(0, 120).replace(/\s+/g, " ")}`
    } catch (e) {
      lastErr = `${endpoint}: ${e}`
    }
    console.warn(`attempt ${attempt + 1} failed: ${lastErr}`)
    await new Promise((r) => setTimeout(r, 2000 * 2 ** attempt))
  }
  throw new Error(`Overpass failed: ${lastErr}`)
}

const ENDPOINTS = ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter", "https://overpass.private.coffee/api/interpreter"]

/** Splits a polyline into runs that stay within `r` of the origin, keeping one point past each crossing. */
function cutToRadius(pts: XY[], r: number): XY[][] {
  const inside = pts.map((p) => Math.hypot(p[0], p[1]) <= r)
  const runs: XY[][] = []
  let cur: XY[] = []
  // Keep every segment with at least one end inside; consecutive kept segments form one run.
  for (let i = 0; i + 1 < pts.length; i++) {
    if (inside[i] || inside[i + 1]) {
      if (!cur.length) cur.push(pts[i])
      cur.push(pts[i + 1])
    } else if (cur.length) {
      runs.push(cur)
      cur = []
    }
  }
  if (cur.length >= 2) runs.push(cur)
  return runs
}

function render(paths: [number, number[]][], dropMinorService: boolean, counts: Record<string, number>, ptsTotal: number): string {
  const rows = paths.map(([k, flat]) => `[${k},[${flat.join(",")}]]`)
  return `// GENERATED by Retrospecs/tools/bake-paths.ts — do not edit by hand.
// Map data (c) OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).
// ${paths.length} polylines within ${BAKE_RADIUS_M} m of Huang (roads ${counts.road}, roads with bike lanes ${counts.roadBikeLane}, bike ${counts.bike}, foot ${counts.foot}); ${ptsTotal} points; Douglas-Peucker ${SIMPLIFY_M} m${dropMinorService ? "; parking aisles and driveways dropped" : ""}.
// Coordinates use the same origin and projection as CampusData.ts (decimetres east, north of the origin).

export const PATHS_RADIUS_M = ${BAKE_RADIUS_M}

/** Kind codes (first element of each BakedPath). */
export const PATH_ROAD = ${KIND_ROAD}
export const PATH_BIKE = ${KIND_BIKE}
export const PATH_FOOT = ${KIND_FOOT}
/** A road with a painted bike lane: drawn as a road plus a dashed bike stripe. */
export const PATH_ROAD_BIKELANE = ${KIND_ROAD_BIKELANE}

/** [kind, polylineXY (decimetres east,north)] */
export type BakedPath = [number, number[]]

export const PATHS: BakedPath[] = [
${rows.join(",\n")}
]
`
}

async function main() {
  const osm = await loadOsm(process.argv.includes("--refresh"))
  const ways = osm.elements.filter((e) => e.type === "way" && e.geometry && e.geometry.length >= 2)
  const dm = (v: number) => Math.round(v * 10)

  for (const dropMinorService of [false, true]) {
    const paths: [number, number[]][] = []
    const counts = {road: 0, roadBikeLane: 0, bike: 0, foot: 0}
    const wayCounts = {road: 0, roadBikeLane: 0, bike: 0, foot: 0}
    let ptsTotal = 0
    for (const w of ways) {
      const kind = classifyWay(w.tags || {}, {dropMinorService})
      if (kind < 0) continue
      const pts: XY[] = w.geometry!.map((g) => {
        const en = latLonToEN(g.lat, g.lon)
        return [en.e, en.n]
      })
      const runs = cutToRadius(pts, BAKE_RADIUS_M)
      if (!runs.length) continue
      const name = kind === KIND_ROAD ? "road" : kind === KIND_ROAD_BIKELANE ? "roadBikeLane" : kind === KIND_BIKE ? "bike" : "foot"
      wayCounts[name]++
      for (const run of runs) {
        const simple = simplifyDP(run, SIMPLIFY_M)
        const flat: number[] = []
        for (const p of simple) {
          const x = dm(p[0]), y = dm(p[1])
          if (flat.length && flat[flat.length - 2] === x && flat[flat.length - 1] === y) continue
          flat.push(x, y)
        }
        if (flat.length < 4) continue
        paths.push([kind, flat])
        counts[name]++
        ptsTotal += flat.length / 2
      }
    }
    // Draw order inside the file does not matter; sort by kind so the file diffs stay readable.
    paths.sort((a, b) => a[0] - b[0])
    const src = render(paths, dropMinorService, counts, ptsTotal)
    const bytes = Buffer.byteLength(src, "utf8")
    console.log(`${dropMinorService ? "without" : "with"} parking aisles: ${(bytes / 1024).toFixed(0)} KB, ${ptsTotal} points; ways road ${wayCounts.road}, road+bike lane ${wayCounts.roadBikeLane}, bike ${wayCounts.bike}, foot ${wayCounts.foot}; polylines ${paths.length}`)
    if (bytes <= MAX_BYTES || dropMinorService) {
      if (bytes > MAX_BYTES) console.warn(`warning: ${(bytes / 1024).toFixed(0)} KB is over the ${MAX_BYTES / 1024} KB target`)
      mkdirSync(dirname(OUT), {recursive: true})
      writeFileSync(OUT, src)
      console.log(`wrote ${OUT}`)
      return
    }
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
