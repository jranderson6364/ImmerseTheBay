const hexRgb = (hex: string): [number, number, number] => {
  const h = hex.replace("#", "")
  return [0, 2, 4].map((i) => Math.round((parseInt(h.slice(i, i + 2), 16) / 255) * 1000) / 1000) as [number, number, number]
}

class Mats {
  list: GMaterial[] = []
  private ix = new Map<PaletteKey, number>()
  get(k: PaletteKey): number {
    if (!this.ix.has(k)) {
      this.list.push({name: k, rgb: hexRgb(PALETTE[k])})
      this.ix.set(k, this.list.length - 1)
    }
    return this.ix.get(k)!
  }
}

type V3 = {x: number; y: number; z: number}
const arr3 = (v: V3): [number, number, number] => [v.x, v.y, v.z]

function poseChanges(e: Experience, frameT: number): {moving: string[]; hidden: string[]; still: string[]} {
  const base = e.poses(0)
  const moved = new Set<number>()
  const end = Math.max(20, e.loop, e.settle + 5)
  for (let t = 0; t <= end; t += 0.1) {
    e.poses(t).forEach((p, i) => {
      const b = base[i]
      const d = Math.abs(p.pos.x - b.pos.x) + Math.abs(p.pos.y - b.pos.y) + Math.abs(p.pos.z - b.pos.z) +
        Math.abs(p.rot.x - b.rot.x) + Math.abs(p.rot.y - b.rot.y) + Math.abs(p.rot.z - b.rot.z) + Math.abs(p.rot.w - b.rot.w) +
        Math.abs(p.scale.x - b.scale.x) + Math.abs(p.scale.y - b.scale.y) + Math.abs(p.scale.z - b.scale.z)
      if (d > 1e-4) moved.add(i)
    })
  }
  const fp = e.poses(frameT)
  const moving: string[] = [], hidden: string[] = [], still: string[] = []
  e.nodes.forEach((n, i) => {
    ;(moved.has(i) ? moving : still).push(n.name)
    if (Math.max(fp[i].scale.x, fp[i].scale.y, fp[i].scale.z) < 0.01) hidden.push(n.name)
  })
  return {moving, hidden, still}
}

/** Root that turns the design frame (front = +Z) to face -Z and puts the pivot at the bottom centre. */
function rooted(name: string, children: GNode[]): GNode {
  const root: GNode = {name, rotation: [0, 1, 0, 0], children}
  const b = treeBounds(root)
  root.translation = [-(b.min[0] + b.max[0]) / 2, -b.min[1], -(b.min[2] + b.max[2]) / 2]
  return root
}

function experienceTree(e: Experience, t: number, rootName: string, mats: Mats): GNode {
  const poses = e.poses(t)
  const kids: GNode[] = e.nodes.map((n, i) => {
    const p = poses[i]
    return {
      name: n.name,
      translation: arr3(p.pos),
      rotation: [p.rot.x, p.rot.y, p.rot.z, p.rot.w],
      scale: arr3(p.scale),
      prims: [{chunk: Exp.buildNode(n), material: mats.get(EXP_TO_PALETTE[n.color] || "cream")}]
    }
  })
  return rooted(rootName, kids)
}

/** Huang: the $30M money pile (Core/Money.ts) with the graphics card (Core/Products.ts) beside it, mid-explode. */
const HUANG_PILE_WIDTH_CM = 30
const HUANG_CARD_SCALE = 0.4
const HUANG_CARD_EXPLODE_T = 0.55
const HUANG_GAP_CM = 3

function huangTree(mats: Mats): {tree: GNode; info: string[]} {
  const gift = giftFor("huang")
  if (!gift) throw new Error("no sourced gift for huang")
  const layout = billsToStack(gift.amountUSD)
  const pile = buildMoneyPile(layout)
  const merged: Record<string, MeshChunk> = {}
  for (const g of MONEY_GROUPS) {
    const verts: number[] = [], idx: number[] = []
    for (const t of pile.towers) for (const c of t.groups[g]) {
      const base = verts.length / 8
      for (let i = 0; i < c.verts.length; i += 8) verts.push(c.verts[i] + t.position.x, c.verts[i + 1] + t.position.y, c.verts[i + 2] + t.position.z, c.verts[i + 3], c.verts[i + 4], c.verts[i + 5], 0, 0)
      for (const i of c.idx) idx.push(i + base)
    }
    merged[g] = {verts, idx}
  }
  const names: Record<string, string> = {bill: "bills", billTop: "bill_tops", band: "bands", pallet: "pallets"}
  const pileScale = HUANG_PILE_WIDTH_CM / Math.max(layout.footprint.widthCm, layout.footprint.depthCm)
  const pileNode: GNode = {
    name: "money_pile",
    scale: [pileScale, pileScale, pileScale],
    children: MONEY_GROUPS.map((g) => ({name: names[g], prims: [{chunk: merged[g], material: mats.get(MONEY_TO_PALETTE[g])}]}))
  }
  const pb = treeBounds(pileNode)

  const card = productById("graphics_card")
  if (!card) throw new Error("no graphics_card product")
  const parts: GNode[] = card.parts.map((p) => ({
    name: p.name,
    translation: arr3(explodedPosition(p, HUANG_CARD_EXPLODE_T)),
    prims: [{chunk: buildPart(p), material: mats.get(PRODUCT_TO_PALETTE[p.color] || "cream")}]
  }))
  const cardNode: GNode = {name: "graphics_card", scale: [HUANG_CARD_SCALE, HUANG_CARD_SCALE, HUANG_CARD_SCALE], children: parts}
  const cb = treeBounds(cardNode)
  // Stand the card on the ground to the right of the pile, front faces aligned.
  cardNode.translation = [pb.max[0] + HUANG_GAP_CM - cb.min[0], -cb.min[1], (pb.min[2] + pb.max[2]) / 2 - (cb.min[2] + cb.max[2]) / 2]
  return {
    tree: rooted("huang", [pileNode, cardNode]),
    info: [
      `Money pile: $${gift.amountUSD / 1e6} million in $1 bills (fact ${gift.factId}): ${layout.skids} skids in ${layout.towers.length} towers, real size ${(layout.footprint.widthCm / 100).toFixed(1)} x ${(layout.footprint.depthCm / 100).toFixed(1)} x ${(layout.footprint.heightCm / 100).toFixed(1)} m, shown at scale ${pileScale.toFixed(4)}.`,
      `The runtime builds one object per tower and colour; here the towers are merged per colour (bills, bill_tops, bands, pallets) to stay under 40 meshes.`,
      `Graphics card at ${HUANG_CARD_SCALE}x, exploded to ${HUANG_CARD_EXPLODE_T} of its timeline. Parts: ${card.parts.map((p) => p.name).join(", ")}.`
    ]
  }
}

interface GlbReport {
  id: string
  file: string
  triangles: number
  meshes: number
  primitives: number
  size: [number, number, number]
  checks: string[]
  validator: string
  ok: boolean
}

let validator: any = null
try {
  validator = await import("gltf-validator")
} catch {
  validator = null
}

async function emitGlb(id: string, tree: GNode, mats: Mats): Promise<GlbReport> {
  const {bytes} = writeGlb(tree, mats.list)
  const file = join(ART, id, `${id}_3d.glb`)
  out(file, bytes)
  const c = checkGlb(bytes)
  const size: [number, number, number] = [0, 1, 2].map((k) => Math.round((c.bounds.max[k] - c.bounds.min[k]) * 10) / 10) as [number, number, number]
  const checks = [...c.errors]
  const across = Math.max(size[0], size[2])
  if (across < 30 || across > 60) checks.push(`FAIL size: ${across} cm across (want 30-60)`)
  if (c.triangles >= 15000) checks.push(`FAIL triangles: ${c.triangles} (want < 15000)`)
  if (c.primitives >= 40) checks.push(`FAIL meshes: ${c.primitives} draw calls (want < 40)`)
  const cx = (c.bounds.min[0] + c.bounds.max[0]) / 2, cz = (c.bounds.min[2] + c.bounds.max[2]) / 2
  if (Math.abs(cx) > 0.05 || Math.abs(cz) > 0.05 || Math.abs(c.bounds.min[1]) > 0.05) checks.push(`FAIL pivot: centre ${cx.toFixed(2)}, ${cz.toFixed(2)}, min y ${c.bounds.min[1].toFixed(2)}`)
  let vtxt = "gltf-validator not available"
  if (validator) {
    try {
      const r = await validator.validateBytes(bytes, {maxIssues: 50})
      const n = r.issues
      vtxt = `gltf-validator ${r.validatorVersion}: ${n.numErrors} errors, ${n.numWarnings} warnings, ${n.numInfos} infos, ${n.numHints} hints`
      if (n.numErrors > 0) {
        checks.push("FAIL gltf-validator errors: " + n.messages.filter((m: any) => m.severity === 0).slice(0, 5).map((m: any) => `${m.code} ${m.pointer || ""}`).join("; "))
      }
      const warn = n.messages.filter((m: any) => m.severity === 1).map((m: any) => m.code)
      if (warn.length) vtxt += ` (${[...new Set(warn)].join(", ")})`
    } catch (e) {
      vtxt = "gltf-validator failed to run: " + e
    }
  }
  return {id, file: `${id}_3d.glb`, triangles: c.triangles, meshes: c.meshes, primitives: c.primitives, size, checks, validator: vtxt, ok: checks.length === 0}
}

