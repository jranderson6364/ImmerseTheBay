let manifest: Record<string, string> = {}
try {
  manifest = JSON.parse(readFileSync(MANIFEST, "utf8"))
} catch {
  manifest = {}
}
const kept: string[] = []
const written: string[] = []
const sha = (b: Uint8Array | string) => createHash("sha256").update(b).digest("hex")

function out(path: string, data: Uint8Array | string) {
  const rel = relative(ART, path).replace(/\\/g, "/")
  const h = sha(data)
  if (existsSync(path) && !FORCE) {
    const cur = sha(readFileSync(path))
    const ours = manifest[rel]
    if (cur !== h && (!ours || ours !== cur)) {
      kept.push(rel)
      console.log(`  kept (modified): ${rel}`)
      return
    }
  }
  mkdirSync(dirname(path), {recursive: true})
  writeFileSync(path, data)
  manifest[rel] = h
  written.push(rel)
}

