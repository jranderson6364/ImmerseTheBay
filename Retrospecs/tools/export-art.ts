function tier2Spec(card: Card): CardArtSpec {
  const theme = card.facts[0]?.theme || "fun"
  for (const [tag, m] of TAG_MOTIF) if (card.tags.indexOf(tag) >= 0) return {motif: m, accent: THEME_ACCENT[theme]}
  return {motif: theme as Motif, accent: THEME_ACCENT[theme]}
}

const factSpec = (f: Fact): CardArtSpec => ({motif: f.theme as Motif, accent: THEME_ACCENT[f.theme]})

function renderPng(svg: string): Uint8Array {
  const r = new Resvg(svg, {fitTo: {mode: "original"}, font: {loadSystemFonts: false}, background: "rgba(0,0,0,0)"})
  const img = r.render()
  if (img.width !== CARD_W || img.height !== CARD_H) throw new Error(`card rendered at ${img.width}x${img.height}`)
  // Posterized re-encode keeps the 57+ cards well under the Art folder budget (about 15 MB).
  return encodePng(new Uint8Array(img.pixels), img.width, img.height)
}

function longestFact(card: Card): Fact {
  return card.facts.reduce((a, b) => (b.text.length > a.text.length ? b : a), card.facts[0])
}

