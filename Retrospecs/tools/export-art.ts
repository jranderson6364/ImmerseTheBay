/**
 * Placeholder art export for the Retrospecs Lens: one folder per card under Assets/Retrospecs/Art/<card id>/ with
 *   <id>_3d.glb                 Tier 1 only: the building's procedural 3D element, posed at a representative frame
 *   <id>_card_<fact id>.png     Tier 1: one card per fact      | <id>_card.png  Tier 2: one card per building
 *   <id>_mockup.svg             where the title, namesake line and fact text go (real Cards.ts text)
 *   README.txt                  moving parts, animation length, file list
 * A designer can replace any file with one of the same name.
 *
 * Run from the repo root:  bun Retrospecs/tools/export-art.ts            (add --force to overwrite edited files)
 * Repeatable and deterministic. It overwrites its own outputs, but a file whose hash no longer matches what this
 * script last wrote (tools/art-manifest.json) is treated as designer art and kept, unless --force is given.
 *
 * Reads Core/*.ts only; never edits them. Experiences are looked up at run time, so Tier 1 buildings without one
 * (for example varian or clark while they're being written) are skipped with a message and picked up on a rerun.
 */

