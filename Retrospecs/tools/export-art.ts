const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f)
    const s = statSync(p)
    if (s.isDirectory()) walk(p)
    else {
      const ext = f.endsWith(".meta") ? ".meta" : f.slice(f.lastIndexOf("."))
      counts[ext] = counts[ext] || {n: 0, bytes: 0}
      counts[ext].n++
      counts[ext].bytes += s.size
      total += s.size
    }
  }
}
