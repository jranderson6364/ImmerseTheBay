/**
 * narration.json -> Assets/Retrospecs/Data/NarrationData.ts (the lens can't read JSON files at runtime).
 * Run: bun Retrospecs/tools/build-narration.ts
 * Each segment gets a stable clip name `<id>_<index>` that matches the baked ElevenLabs audio (bake-voice.ts).
 */
import {existsSync, readFileSync, writeFileSync} from "fs"
import {join} from "path"

const here = import.meta.dir
const src = JSON.parse(readFileSync(join(here, "narration", "narration.json"), "utf8"))
const out: string[] = []
out.push("// GENERATED by Retrospecs/tools/build-narration.ts from tools/narration/narration.json. Do not edit by hand.")
out.push("")
out.push("export interface NarrationSegment {")
out.push("  kind: \"overview\" | \"more\"")
out.push("  /** Baked audio clip name (asset name without extension). */")
out.push("  clip: string")
out.push("  text: string")
out.push("  sources: string[]")
out.push("}")
out.push("")
out.push("export const NARRATION: Record<string, NarrationSegment[]> = {")
for (const l of src.landmarks) {
  const segs = l.segments.map((s: any, i: number) => ({kind: s.kind, clip: `${l.id}_${i}`, text: s.text, sources: s.sources}))
  out.push(`  ${JSON.stringify(l.id)}: ${JSON.stringify(segs)},`)
}
out.push("}")
out.push("")
out.push("export function narrationFor(id: string): NarrationSegment[] {")
out.push("  return NARRATION[id] || []")
out.push("}")
out.push("")
writeFileSync(join(here, "..", "Assets", "Retrospecs", "Data", "NarrationData.ts"), out.join("\n"))
console.log(`wrote ${src.landmarks.length} landmarks`)

// Baked clips that exist on disk, as lazy requireAsset() calls (literal paths, so Lens Studio bundles them and no
// Inspector wiring is needed). Re-run this after bake-voice.ts.
const audioDir = join(here, "..", "Assets", "Retrospecs", "Audio", "narration")
const clips: string[] = []
for (const l of src.landmarks) {
  l.segments.forEach((_: any, i: number) => {
    if (existsSync(join(audioDir, `${l.id}_${i}.mp3`))) clips.push(`${l.id}_${i}`)
  })
}
const c: string[] = []
c.push("// GENERATED by Retrospecs/tools/build-narration.ts (lists the baked mp3s in Audio/narration). Do not edit by hand.")
c.push("")
c.push("export const NARRATION_CLIPS: Record<string, () => AudioTrackAsset> = {")
for (const k of clips) c.push(`  ${k}: () => requireAsset("../Audio/narration/${k}.mp3") as AudioTrackAsset,`)
c.push("}")
c.push("")
writeFileSync(join(here, "..", "Assets", "Retrospecs", "Data", "NarrationClips.ts"), c.join("\n"))
console.log(`wrote ${clips.length} baked clip references`)
